function applyTranslations(language = localStorage.getItem('jobhunt-language') || 'en') {
    const dictionary = translations[language] || translations.en;
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.dataset.i18n;
        if (dictionary[key]) element.textContent = dictionary[key];
    });
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    const textNodes = [];
    while (walker.nextNode()) textNodes.push(walker.currentNode);
    textNodes.forEach(node => {
        const key = node.nodeValue.trim();
        if (key && dictionary[key]) node.nodeValue = node.nodeValue.replace(key, dictionary[key]);
    });
    document.documentElement.lang = language;
}

function initLanguageControls() {
    const languageSection = document.getElementById('country-language');
    let languageSelect = document.getElementById('language-select') || languageSection?.querySelector('select');
    if (languageSection) {
        const heading = languageSection.querySelector('h2');
        const description = languageSection.querySelector('p:not(.eyebrow)');
        if (heading) heading.textContent = 'Language';
        if (description) description.textContent = 'Language: English';
    }
    if (languageSelect) languageSelect.remove();
    const savedLanguage = 'en';
    localStorage.setItem('jobhunt-language', 'en');
    applyTranslations(savedLanguage);
}

if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', initLanguageControls);
else initLanguageControls();
